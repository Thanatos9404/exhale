    const advisory = buildCommunityAdvisory(lidDay, DELHI, 'en');
    const [first, second] = lidDay.lid.spans;
    expect(advisory).toMatchObject({ place: 'New Delhi, India', date: '23 Nov 2026' });
    expect(advisory.category).toBe(lidDay.risk.label);
    expect(advisory.facts[0]).toContain(`AQI now: ${lidDay.risk.aqi}`);
    expect(advisory.facts[1]).toContain(`${first!.start} to ${first!.end}`);
