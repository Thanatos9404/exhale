import fc from 'fast-check';
import { describe, expect, it } from 'vitest';
import type { AirSnapshot, HourPoint } from '@/lib/air/types';
import { buildPlan, type PlanResult } from '@/lib/planner/engine';
import { DEFAULT_HOUSEHOLD, type Household } from '@/lib/profile/schema';
import { makeHourly, makeSnapshot } from '@/test/fixtures';
import {
  ADVISORY_MAX_CHARS,
  buildCommunityAdvisory,
  type AdvisoryLanguage,
  type PublicPlanFacts,
} from './advisory';
import { MESSAGES } from './messages';

/**
 * The bulletin is checked against plans the real engine builds from synthetic days, so every
 * hour and number asserted here is one the engine computed.
 */

const NOW = new Date('2026-11-23T00:00:00Z');
const LANGUAGES: AdvisoryLanguage[] = ['en', 'hi'];
const DEVANAGARI = /[\u0900-\u097F]/;

/** A snapshot whose hourly series is the default winter day with some readings replaced. */
function snapshotWith(edit: (hour: HourPoint, hod: number) => Partial<HourPoint>): AirSnapshot {
  const hourly = makeHourly().map((hour) => ({
    ...hour,
    ...edit(hour, Number(hour.time.slice(11, 13))),
  }));
  return makeSnapshot({ hourly });
}

function planFor(air: AirSnapshot, household: Household = DEFAULT_HOUSEHOLD): PlanResult {
  return buildPlan(household, air, NOW);
}

const DELHI = makeSnapshot().place;
const lidDay = planFor(makeSnapshot());
/** Clean air all day: PM2.5 of 8 µg/m³ under a deep, breezy mixing layer. */
const cleanDay = planFor(
  snapshotWith(() => ({ pm25: 8, pm10: 13, no2: 10, o3: 20, blh: 1500, wind: 15 })),
);
/** A night-time lid, with an early afternoon that is clean enough for children. */
const lidWithCleanAfternoon = planFor(
  snapshotWith((_, hod) => ({ pm25: hod >= 13 && hod <= 15 ? 20 : 150 })),
);
/** No PM2.5 forecast at all, so there is neither a clean nor a dirty window. */
const noPm25 = planFor(snapshotWith(() => ({ pm25: null })));
const noBoundaryLayer = planFor(snapshotWith(() => ({ blh: null })));
/** Polluted but well mixed: no lid forms. */
const pollutedNoLid = planFor(snapshotWith(() => ({ blh: 900, wind: 14 })));

