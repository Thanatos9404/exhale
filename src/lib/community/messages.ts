/**
 * Wording of the neighbourhood air bulletin in English and Hindi. This module only phrases
 * facts: every hour and number is handed in by `advisory.ts`, which reads them from the plan.
 * The Hindi is written the way a resident would post to a housing-society group, with Western
 * digits and the terms AQI and PM2.5 left as they are.
 */
import type { AqiLevel } from '../air/aqi.js';
import type { AqiStandard } from '../air/types.js';

/** Languages the bulletin is written in. */
export type AdvisoryLanguage = 'en' | 'hi';

/** A run of hours as local "HH:00" labels. */
export interface HourRange {
  start: string;
  end: string;
}

/** Every phrase of the bulletin for one language. */
export interface AdvisoryMessages {
  /** Month names, January first. */
  months: readonly string[];
  /** Name of each AQI scale. */
  scale: Record<AqiStandard, string>;
  /** Category names by level, or null to use the plan's own English label. */
  categories: Record<AqiStandard, readonly string[]> | null;
  title: (place: string, date: string | null) => string;
  aqi: (aqi: number, category: string, scale: string) => string;
  range: (hours: HourRange) => string;
  /** Joins the listed ranges and says how many more were left out. */
  list: (ranges: readonly string[], more: number) => string;
  lid: (hours: string, minBlh: number) => string;
  noLid: string;
  lidUnknown: string;
  cleanest: (hours: string, pm25: number) => string;
  noForecast: string;
  heading: string;
  cleanHeading: string;
  burnLid: string;
  burn: string;
  playWindow: (hours: string) => string;
  playIndoors: (limit: number) => string;
  playNoForecast: string;
  airingLid: (hours: string) => string;
  airing: (hours: string) => string;
  airingNoForecast: string;
  commutePeak: (hours: string) => string;
  commute: string;
  checkPeak: (hours: string) => string;
  check: string;
  cleanOutdoors: string;
  cleanKeep: string;
  source: string;
}

/** "a", "a and b" or "a, b and c" with the language's own word for "and". */
function joinWith(and: string, items: readonly string[]): string {
  const last = items.at(-1) ?? '';
  if (items.length < 2) return last;
  return `${items.slice(0, -1).join(', ')} ${and} ${last}`;
}

