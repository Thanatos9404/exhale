/** The bulletin's phrases for each language. */
export const MESSAGES: Record<AdvisoryLanguage, AdvisoryMessages> = { en: EN, hi: HI };

/** The category name to print: translated by level where the language has names, else `label`. */
export function categoryName(
  messages: AdvisoryMessages,
  standard: AqiStandard,
  level: AqiLevel,
  label: string,
): string {
  return messages.categories?.[standard][level] ?? label;
}
